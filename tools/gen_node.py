"""Generate MicroPython wrappers for the plain and text NodeApi functions.

    py -3.14 tools/gen_node.py
"""

from __future__ import annotations

import importlib.util
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "src" / "node_gen.c"


def load_parser():
    path = ROOT / "tools" / "gen_abi.py"
    spec = importlib.util.spec_from_file_location("gen_abi", path)
    if spec is None or spec.loader is None:
        raise SystemExit(f"cannot load {path}")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def c_arg(kind: str, index: int) -> str:
    src = f"a{index}"
    if kind == "int":
        return f"mp_obj_get_int({src})"
    if kind == "u32":
        return f"(uint32_t)mp_obj_get_int({src})"
    if kind == "i64":
        return f"(int64_t)mp_obj_get_int({src})"
    if kind == "double":
        return f"mp_obj_get_float({src})"
    if kind == "float":
        return f"(float)mp_obj_get_float({src})"
    if kind == "cstr":
        return f"nodemp_cstr({src})"
    raise SystemExit(f"unexpected kind {kind}")


def ret_expr(ret: str, call: str) -> str:
    if ret == "void":
        return f"    {call};\n    return mp_const_none;\n"
    if ret in ("int", "int64_t"):
        return f"    return mp_obj_new_int({call});\n"
    if ret == "uint32_t":
        return f"    return mp_obj_new_int_from_uint({call});\n"
    if ret == "double":
        return f"    return mp_obj_new_float({call});\n"
    raise SystemExit(f"unexpected return {ret}")


def fun_macro(nargs: int) -> str:
    if nargs == 0:
        return "MP_DEFINE_CONST_FUN_OBJ_0"
    if nargs == 1:
        return "MP_DEFINE_CONST_FUN_OBJ_1"
    if nargs == 2:
        return "MP_DEFINE_CONST_FUN_OBJ_2"
    if nargs == 3:
        return "MP_DEFINE_CONST_FUN_OBJ_3"
    return "MP_DEFINE_CONST_FUN_OBJ_VAR_BETWEEN"


def emit_function(fn: dict, lines: list[str]) -> None:
    name = fn["name"]
    prefix = [p for p in fn["params"] if p["kind"] not in ("buf", "buflen")]
    nargs = len(prefix)
    if nargs <= 3:
        params = ", ".join(["void"] if nargs == 0 else [f"mp_obj_t a{i}" for i in range(nargs)])
        if nargs == 0:
            params = "void"
        macro_tail = f"auto_{name}_obj, auto_{name}"
        macro = fun_macro(nargs)
    else:
        params = "size_t n_args, const mp_obj_t *args"
        macro = "MP_DEFINE_CONST_FUN_OBJ_VAR_BETWEEN"
        macro_tail = f"auto_{name}_obj, {nargs}, {nargs}, auto_{name}"
    lines.append(f"static mp_obj_t auto_{name}({params}) {{")
    lines.append(f'    nodemp_require(offsetof(NodeApi, {name}), "{name}");')
    if nargs > 3:
        for i in range(nargs):
            lines.append(f"    mp_obj_t a{i} = args[{i}];")
    converted = ", ".join(c_arg(p["kind"], i) for i, p in enumerate(prefix))
    call_args = converted
    if fn["auto"] == "text":
        call = f"g_api->{name}({call_args}{', ' if call_args else ''}"
        lines.append("    char stack[512];")
        lines.append("    char *buf = stack;")
        lines.append("    int owned = 0;")
        lines.append(f"    int n = {call}stack, (int)sizeof stack);")
        lines.append("    if (n < 0) {")
        lines.append(f"        n = {call}NULL, 0);")
        lines.append("        if (n < 0) return mp_const_none;")
        lines.append("        if (n > 8388608) mp_raise_msg(&mp_type_OSError, MP_ERROR_TEXT(\"text result is too large\"));")
        lines.append("        buf = malloc((size_t)n + 1);")
        lines.append("        if (!buf) mp_raise_msg(&mp_type_MemoryError, MP_ERROR_TEXT(\"out of memory\"));")
        lines.append("        owned = 1;")
        lines.append(f"        n = {call}buf, n + 1);")
        lines.append("        if (n < 0) { free(buf); return mp_const_none; }")
        lines.append("    }")
        lines.append("    mp_obj_t text = mp_obj_new_str(buf, (size_t)n);")
        lines.append("    if (owned) free(buf);")
        lines.append("    return text;")
    else:
        call = f"g_api->{name}({call_args})"
        lines.append(ret_expr(fn["ret"], call).rstrip("\n"))
    lines.append("}")
    if nargs <= 3:
        lines.append(f"static {macro}({macro_tail});")
    else:
        lines.append(f"static {macro}({macro_tail});")
    lines.append("")


def render(model: dict) -> str:
    lines = [
        "/* Generated by tools/gen_node.py from node.h. Do not edit. */",
        "#include <stddef.h>",
        "#include <stdlib.h>",
        "",
        "#include \"node_int.h\"",
        "",
        "#include \"py/runtime.h\"",
        "",
    ]
    selected = [fn for fn in model["functions"] if fn["auto"] in ("plain", "text")]
    for fn in selected:
        emit_function(fn, lines)
    lines.append("void nodemp_register_auto(mp_obj_dict_t *dict) {")
    for fn in selected:
        lines.append(f'    nodemp_store(dict, "{fn["name"]}", MP_OBJ_FROM_PTR(&auto_{fn["name"]}_obj));')
    for name, value in model["constants"]:
        lines.append(f'    nodemp_store(dict, "{name}", mp_obj_new_int({value}));')
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def main() -> None:
    parser = load_parser()
    model = parser.parse_header((ROOT / "sdk" / "node.h").read_text(encoding="utf-8"))
    text = render(model)
    OUT.write_text(text, encoding="utf-8", newline="\n")
    autos: dict[str, int] = {}
    for fn in model["functions"]:
        if fn["auto"] in ("plain", "text"):
            autos[fn["auto"]] = autos.get(fn["auto"], 0) + 1
    print(f"wrote {OUT.name}: {autos}")


if __name__ == "__main__":
    sys.exit(main())
